#!/usr/bin/env python3
"""Read-only analysis of NYAO_ENTRY_DIAGNOSTICS.csv; NEVER submits broker orders.

The CSV is generated by the isolated, tester-only diagnostic EA. Entry context is
observed at trade time; MFE/MAE is sampled on ticks received by the running EA.
It does NOT reveal future reversal after a stop. These figures are not evidence
of out-of-sample profitability.
"""
from __future__ import annotations
import argparse
import csv
import datetime as dt
import json
import math
import sys
from collections import defaultdict
from pathlib import Path

EXPECTED = [
    "schema", "ticket", "symbol", "period", "direction", "entry_time", "entry_price",
    "volume", "entry_spread_points", "score", "threshold", "efficiency_20",
    "atr_closed", "trend_range", "trend_ema", "trend_efficiency", "trend_momentum",
    "losing_penalty", "drawdown_pct", "signal_bar", "initial_sl", "initial_tp",
    "exit_time", "exit_price", "exit_reason_code", "exit_comment", "net_profit_usd",
    "mfe_price", "mae_price", "mfe_points", "mae_points", "observed_ticks",
    "max_spread_points", "last_observed_sl", "adverse_sl_gap_price", "status",
]

FIELDS = [
    "volume", "entry_price", "entry_spread_points", "score", "threshold",
    "efficiency_20", "atr_closed", "losing_penalty", "drawdown_pct",
    "exit_price", "net_profit_usd", "mfe_price", "mae_price", "mfe_points",
    "mae_points", "max_spread_points",
]


def safe_num(raw: str, label: str) -> float:
    try:
        value = float(raw)
    except (ValueError, TypeError) as exc:
        raise ValueError(f"Missing or nonnumeric {label}: {raw!r}") from exc
    if not math.isfinite(value):
        raise ValueError(f"Nonfinite {label}: {raw!r}")
    return value


def stats(rows: list[dict]) -> dict:
    p = [r["net_profit_usd"] for r in rows]
    gross = sum(x for x in p if x > 0)
    loss = -sum(x for x in p if x < 0)
    return {
        "trades": len(rows),
        "net_usd": round(sum(p), 2),
        "profit_factor": round(gross / loss, 4) if loss else None,
        "wins": sum(x > 0 for x in p),
        "losses": sum(x < 0 for x in p),
        "breakeven": sum(x == 0 for x in p),
        "mean_usd": round(sum(p) / len(p), 4) if p else None,
    }


def bucket(value: float, edges: tuple[float, ...]) -> str:
    for limit in edges:
        if value < limit:
            return f"<{limit:g}"
    return f">={edges[-1]:g}"


def analyze(path: Path, expected_trades: int | None = None,
            expected_net: float | None = None) -> dict:
    if not path.is_file():
        raise ValueError(f"Missing diagnostic CSV: {path}")
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle, delimiter=",")
        if reader.fieldnames != EXPECTED:
            raise ValueError("CSV header does not match frozen 36-column MQL5 contract")
        raw = list(reader)
    if not raw:
        raise ValueError("Diagnostic CSV is empty")
    tickets = set()
    rows = []
    incomplete = []
    groups: dict[str, dict[str, list]] = {
        "direction": defaultdict(list),
        "efficiency_bin": defaultdict(list),
        "signal_margin_bin": defaultdict(list),
        "spread_bin_points": defaultdict(list),
        "holding_minutes_bin": defaultdict(list),
        "exit_reason_code": defaultdict(list),
    }
    for n, r in enumerate(raw, 2):
        ticket = r.get("ticket", "")
        if ticket in tickets:
            raise ValueError(f"Duplicate ticket {ticket} at CSV row {n}; no dedup guess allowed")
        tickets.add(ticket)
        if r.get("schema") != "1":
            raise ValueError(f"Unknown schema at CSV row {n}")
        status = r.get("status", "")
        if status != "CLOSED":
            incomplete.append({"ticket": ticket, "status": status})
            continue
        try:
            entry = dt.datetime.strptime(r["entry_time"], "%Y.%m.%d %H:%M:%S")
            exit_ = dt.datetime.strptime(r["exit_time"], "%Y.%m.%d %H:%M:%S")
        except (ValueError, KeyError) as exc:
            raise ValueError(f"Invalid date at CSV row {n}: {exc}") from exc
        if exit_ < entry:
            raise ValueError(f"Exit before entry at CSV row {n}")
        if r["direction"] not in ("BUY", "SELL"):
            raise ValueError(f"Invalid side at CSV row {n}")
        if not ticket.isdigit():
            raise ValueError(f"Invalid position ticket at CSV row {n}")
        values = {key: safe_num(r[key], f"{key} row {n}") for key in FIELDS}
        values.update({"ticket": ticket, "direction": r["direction"],
                       "holding_min": (exit_ - entry).total_seconds() / 60.0,
                       "exit_reason_code": r["exit_reason_code"],
                       "entry_time": entry, "exit_time": exit_,
                       "observed_ticks": int(r["observed_ticks"])})
        if values["observed_ticks"] < 0 or values["volume"] <= 0:
            raise ValueError(f"Invalid volume or tick count at CSV row {n}")
        rows.append(values)
        groups["direction"][values["direction"]].append(values)
        groups["efficiency_bin"][bucket(values["efficiency_20"], (0.2, 0.3, 0.5, 0.7))].append(values)
        groups["signal_margin_bin"][bucket(values["score"] - values["threshold"],
                                              (0.5, 1.0, 2.0))].append(values)
        groups["spread_bin_points"][bucket(values["entry_spread_points"],
                                              (100, 250, 500))].append(values)
        groups["holding_minutes_bin"][bucket(values["holding_min"],
                                                (15, 60, 240))].append(values)
        groups["exit_reason_code"][values["exit_reason_code"]].append(values)
    summary = stats(rows)
    if expected_trades is not None and summary["trades"] != expected_trades:
        raise ValueError(f"Trade count mismatch: CSV={summary['trades']} MT5={expected_trades}")
    if expected_net is not None and abs(summary["net_usd"] - expected_net) > 0.02:
        raise ValueError(f"Net mismatch: CSV={summary['net_usd']} MT5={expected_net}")
    anomalies = sorted(
        [r for r in rows if r["mae_price"] >= 2 * r["atr_closed"] > 0],
        key=lambda r: r["mae_price"] / r["atr_closed"], reverse=True,
    )[:20]
    return {
        "verdict": "COMPLETE_READ_ONLY_RECONCILED" if not incomplete else "INCOMPLETE_EVIDENCE",
        "source_csv": str(path),
        "summary": summary,
        "unresolved_positions": incomplete,
        "observed_zero_tick_trades": sum(r["observed_ticks"] == 0 for r in rows),
        "by_category": {name: {key: stats(value) for key, value in sorted(group.items())}
                        for name, group in groups.items()},
        "mae_ge_2_atr_examples": [
            {"ticket": r["ticket"], "side": r["direction"],
             "mae_to_atr": round(r["mae_price"] / r["atr_closed"], 2),
             "net_usd": r["net_profit_usd"]}
            for r in anomalies
        ],
        "method_notes": [
            "No parameters were optimized or changed by the analyzer.",
            "MFE/MAE uses tradable Bid (BUY) and Ask (SELL) observed on ticks during an open position.",
            "The last exit fill is included, but missed intermediate ticks remain possible.",
            "A stop-deal's actual trigger level may differ from last observed SL.",
            "Exit reason code is the native MQL5 deal reason integer, not inferred from comment text.",
            "No post-stop price path is captured. A reversal-to-TP claim cannot be made from this CSV.",
            "Time buckets and correlations are descriptive and do not prove that changing hold time helps.",
        ],
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", type=Path)
    parser.add_argument("--expected-trades", type=int)
    parser.add_argument("--expected-net", type=float)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    try:
        result = analyze(args.csv, args.expected_trades, args.expected_net)
    except (OSError, ValueError) as exc:
        print(f"FORENSIC VALIDATION FAILED: {exc}", file=sys.stderr)
        return 2
    encoded = json.dumps(result, ensure_ascii=False, indent=2, default=str)
    if args.out:
        args.out.write_text(encoded + "\n", encoding="utf-8")
        print(f"Wrote report: {args.out}")
    else:
        print(encoded)
    return 0 if result["verdict"] == "COMPLETE_READ_ONLY_RECONCILED" else 2


if __name__ == "__main__":
    raise SystemExit(main())
